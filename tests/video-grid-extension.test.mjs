import { test } from 'node:test';
import assert from 'node:assert/strict';
import { launchExtension, virtualPad } from './helpers/extension.mjs';

test('grid preferences save, resize the real browse surface and reset independently', { timeout: 60000 }, async t => {
  const { context, options, worker } = await launchExtension(t);
  await options.locator('[data-category-link="display"]').click();
  await options.locator('#gridColumns600').fill('3');
  await options.locator('#gridColumns600').press('Tab');
  await options.waitForFunction(() => !window.__pageDOM.querySelector('fieldset').disabled);
  await options.locator('[data-setting="gridLayout-twoColumns"]').click();
  await options.waitForFunction(() => !window.__pageDOM.querySelector('fieldset').disabled);
  await options.locator('#gridSwitchWidth').fill('720');
  await options.locator('#gridSwitchWidth').press('Tab');
  await options.waitForFunction(() => !window.__pageDOM.querySelector('fieldset').disabled);
  assert.equal(await worker.evaluate(async () => (await chrome.storage.local.get('gridSwitchWidth')).gridSwitchWidth), 720);
  await worker.evaluate(() => chrome.storage.local.set({ autoFullscreen: false }));
  const page = await context.newPage();
  await page.route('https://www.youtube.com/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body><ytd-page-manager><ytd-browse><ytd-rich-item-renderer><a id="thumbnail" href="/watch?v=grid">Grid video</a></ytd-rich-item-renderer></ytd-browse></ytd-page-manager></body></html>' }));
  await page.setViewportSize({ width: 748, height: 900 });
  await page.goto('https://www.youtube.com/feed/custom');
  const pad = await virtualPad(context, page);
  await pad({ connected: true });
  const cards = page.locator('#ytg-browse-grid .cards');
  await cards.waitFor();
  await page.waitForFunction(() => window.__pageDOM.querySelector('#ytg-browse-grid .cards')?.style.gridTemplateColumns === 'repeat(1, minmax(0px, 1fr))');
  await options.locator('[data-setting="gridLayout-twoColumns"]').click();
  await options.waitForFunction(() => !window.__pageDOM.querySelector('fieldset').disabled);
  await options.locator('#gridAutoSwitch').uncheck();
  await page.waitForFunction(() => window.__pageDOM.querySelector('#ytg-browse-grid .cards')?.style.gridTemplateColumns === 'repeat(2, minmax(0px, 1fr))');
  assert.equal(await cards.getAttribute('data-horizontal'), 'true');
  await options.locator('#gridDoubleCover').fill('65');
  await options.locator('#gridDoubleCover').dispatchEvent('change');
  await page.waitForFunction(() => window.__pageDOM.querySelector('#ytg-browse-grid .cards')?.style.getPropertyValue('--ytg-cover-width') === '65%');
  await options.locator('[data-setting="gridLayout-adaptive"]').click();
  await page.setViewportSize({ width: 1072, height: 900 });
  await page.waitForFunction(() => window.__pageDOM.querySelector('#ytg-browse-grid .cards')?.style.gridTemplateColumns === 'repeat(3, minmax(0px, 1fr))');
  assert.equal(await cards.getAttribute('data-horizontal'), 'false');
  await options.locator('[data-setting="resetVideoGrid"]').click();
  await options.waitForFunction(() => window.__pageDOM.querySelector('#gridColumns600').value === '2' && !window.__pageDOM.querySelector('fieldset').disabled);
  assert.equal(await options.locator('#gridDoubleCover').inputValue(), '65');
  assert.equal(await worker.evaluate(async () => (await chrome.storage.local.get('autoFullscreen')).autoFullscreen), false);
  await options.screenshot({ path: 'output/playwright/video-grid-settings.png', fullPage: true });
});
