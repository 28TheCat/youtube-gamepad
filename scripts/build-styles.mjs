import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { controllerAssets } from './controller-assets.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function styleSource() {
  const assets = controllerAssets(root);
  const images = new Map();
  const artwork = new Map();
  const image = path => {
    if (!images.has(path)) {
      const bytes = readFileSync(resolve(root, path));
      if (createHash('sha256').update(bytes).digest('hex') !== assets.files[path]?.sha256) throw new Error(`Controller artwork changed: ${path}`);
      const value = `url("data:image/svg+xml;base64,${bytes.toString('base64')}")`;
      if (!artwork.has(value)) artwork.set(value, `--ytg-artwork-${artwork.size}`);
      images.set(path, `var(${artwork.get(value)})`);
    }
    return images.get(path);
  };
  const rules = Object.entries(assets.profiles).flatMap(([family, keys]) => {
    const selectors = Object.entries(keys).map(([key, path]) =>
      `[data-ytg-family="${family}"][data-ytg-first-key="${key}"]{--ytg-first-image:${image(path)}}\n[data-ytg-family="${family}"][data-ytg-second-key="${key}"]{--ytg-second-image:${image(path)}}`);
    return selectors;
  }).join('\n');
  const readCss = file => readFileSync(resolve(root, file), 'utf8').replace(/\r\n/g, '\n');
  // Define artwork once per document/ShadowRoot; prompt rules reference it.
  const definitions = [...artwork].map(([value, name]) => `${name}:${value}`).join(';');
  const controller = readCss('src/ui/controller.css') + `\n:host,:root{${definitions}}\n` + rules;
  const styles = Object.fromEntries(['menu', 'watch'].map(name => [name, readCss(`src/ui/${name}.css`)]));
  const layoutImage = readFileSync(resolve(root, 'assets/controller/layout.svg')).toString('base64');
  styles.menu += `\n#inline-settings .inline-controller-map::before{background-image:url("data:image/svg+xml;base64,${layoutImage}")}`;
  return '// Generated by scripts/build-styles.mjs. Edit src/ui/*.css instead.\n' +
    `export let YTGamepadStyles: { menu: string; watch: string; controller: string };\n(() => {\n` +
    `  const controller = ${JSON.stringify(controller)};\n` +
    `  const styles = ${JSON.stringify(styles)};\n` +
    `  YTGamepadStyles = { menu: styles.menu + '\\n' + controller, watch: styles.watch + '\\n' + controller, controller };\n})();\n`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, 'src/ui/styles.ts'), styleSource());
  console.log('Shadow UI styles generated.');
}
