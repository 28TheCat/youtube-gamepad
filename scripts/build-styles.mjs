import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function styleSource() {
  const assets = JSON.parse(readFileSync(resolve(root, 'assets/controller/kenney.json'), 'utf8'));
  const images = new Map();
  const image = path => {
    if (!images.has(path)) {
      const bytes = readFileSync(resolve(root, path));
      if (createHash('sha256').update(bytes).digest('hex') !== assets.files[path]?.sha256) throw new Error(`Controller artwork changed: ${path}`);
      images.set(path, `url("data:image/svg+xml;base64,${bytes.toString('base64')}")`);
    }
    return images.get(path);
  };
  const rules = Object.entries(assets.profiles).flatMap(([family, keys]) => {
    const selectors = Object.entries(keys).map(([key, path]) =>
      `[data-ytg-family="${family}"][data-ytg-first-key="${key}"]{--ytg-first-image:${image(path)}}\n[data-ytg-family="${family}"][data-ytg-second-key="${key}"]{--ytg-second-image:${image(path)}}`);
    return selectors;
  }).join('\n');
  const readCss = file => readFileSync(resolve(root, file), 'utf8').replace(/\r\n/g, '\n');
  const controller = readCss('ui/controller.css') + '\n' + rules;
  const styles = Object.fromEntries(['menu', 'watch'].map(name => [name, readCss(`ui/${name}.css`) + '\n' + controller]));
  styles.controller = controller;
  const layoutImage = readFileSync(resolve(root, 'assets/controller/layout.svg')).toString('base64');
  styles.menu += `\n#inline-settings .inline-controller-map{background-image:url("data:image/svg+xml;base64,${layoutImage}")}`;
  return '// Generated by scripts/build-styles.mjs. Edit ui/*.css instead.\n' +
    `(() => { window.YTGamepadStyles = ${JSON.stringify(styles)}; })();\n`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, 'ui/styles.js'), styleSource());
  console.log('Shadow UI styles generated.');
}
