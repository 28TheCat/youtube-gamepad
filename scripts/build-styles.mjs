import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function styleSource() {
  const styles = Object.fromEntries(['menu', 'watch'].map(name => [name, readFileSync(resolve(root, `ui/${name}.css`), 'utf8')]));
  return '// Generated by scripts/build-styles.mjs. Edit ui/*.css instead.\n' +
    `(() => { window.YTGamepadStyles = ${JSON.stringify(styles)}; })();\n`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, 'ui/styles.js'), styleSource());
  console.log('Shadow UI styles generated.');
}
